/**
 * Generates supabase/migrations/0005_seed_catalogue.sql from the bundled demo catalogue.
 * Run: npm run db:seed:generate. Re-running regenerates the file deterministically.
 */
import { writeFileSync } from 'node:fs';
import { BUNDLED_COMPONENTS, BUNDLED_PROJECTS } from '../src/data/catalog';

const q = (v: string | number | boolean | null) => {
  if (v === null) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${v.replace(/'/g, "''")}'`;
};
const arr = (xs: string[]) => `array[${xs.map((x) => q(x)).join(',')}]::text[]`;
const json = (xs: unknown) => `${q(JSON.stringify(xs))}::jsonb`;

const lines: string[] = [];
lines.push('-- 0005: demo catalogue seed. GENERATED by scripts/generate-seed.ts. Do not edit by hand.');
lines.push('-- Re-running is safe: rows are upserted by id.');
lines.push('');
lines.push('insert into public.components (id, name, category, description, unit_price, weight_grams, specs, compatibility) values');
lines.push(
  BUNDLED_COMPONENTS.map(
    (c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.category)}, ${q(c.description)}, ${c.unitPrice}, ${c.weightGrams}, ${q(c.specs)}, ${q(c.compatibility)})`,
  ).join(',\n') +
    '\non conflict (id) do update set name = excluded.name, category = excluded.category, description = excluded.description,' +
    '\n  unit_price = excluded.unit_price, weight_grams = excluded.weight_grams, specs = excluded.specs, compatibility = excluded.compatibility;',
);
lines.push('');
lines.push(
  'insert into public.products (id, name, aliases, category, description, difficulty, duration_minutes, new_product_price, consumables_cost, icon, requires_spec_check, instructions, safety_notes, compatibility_notes) values',
);
lines.push(
  BUNDLED_PROJECTS.map(
    (p) =>
      `  (${q(p.id)}, ${q(p.name)}, ${arr(p.aliases)}, ${q(p.category)}, ${q(p.description)}, ${q(p.difficulty)}, ${p.durationMinutes}, ${p.newProductPrice}, ${p.consumablesCost}, ${q(p.icon)}, ${q(p.requiresSpecCheck)}, ${json(p.instructions)}, ${json(p.safety)}, ${json(p.compatibilityNotes)})`,
  ).join(',\n') +
    '\non conflict (id) do update set name = excluded.name, aliases = excluded.aliases, category = excluded.category, description = excluded.description,' +
    '\n  difficulty = excluded.difficulty, duration_minutes = excluded.duration_minutes, new_product_price = excluded.new_product_price,' +
    '\n  consumables_cost = excluded.consumables_cost, icon = excluded.icon, requires_spec_check = excluded.requires_spec_check,' +
    '\n  instructions = excluded.instructions, safety_notes = excluded.safety_notes, compatibility_notes = excluded.compatibility_notes, updated_at = now();',
);
lines.push('');
lines.push('-- Requirements: replace per product so removed requirements do not linger.');
for (const p of BUNDLED_PROJECTS) {
  lines.push(`delete from public.product_requirements where product_id = ${q(p.id)};`);
  const rows = p.requirements.map(
    (r) => `  (${q(p.id)}, ${q(r.componentId)}, ${r.quantity}, ${arr(r.alternatives ?? [])}, ${q(Boolean(r.critical))})`,
  );
  lines.push('insert into public.product_requirements (product_id, component_id, required_quantity, compatible_alternatives, is_critical) values');
  lines.push(rows.join(',\n') + ';');
}
lines.push('');

const out = new URL('../supabase/migrations/0005_seed_catalogue.sql', import.meta.url);
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${BUNDLED_COMPONENTS.length} components and ${BUNDLED_PROJECTS.length} products`);
